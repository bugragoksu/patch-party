// Turns the shared catalog into a TypeScript module so it ships inside the
// compiled functions (no JSON import attributes: the Cloud Functions runtime
// loads this package as CommonJS).
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const catalog = JSON.parse(readFileSync(resolve(root, '../shared/catalog/interests.json'), 'utf8'));
const target = resolve(root, 'src/generated/catalog.ts');
mkdirSync(dirname(target), { recursive: true });
writeFileSync(
  target,
  `// GENERATED by scripts/sync-shared.mjs from shared/catalog/interests.json. Do not edit.\nexport const catalog = ${JSON.stringify(catalog, null, 2)} as const;\n`,
);
