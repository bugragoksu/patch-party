#!/usr/bin/env node
// Generates app/lib/core/domain/catalog.g.dart from shared/catalog/interests.json.
// Run `dart format` on the output afterwards (CI does, then fails if the
// committed file differs).
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const catalog = JSON.parse(readFileSync(resolve(root, 'shared/catalog/interests.json'), 'utf8'));
const q = (s) => `'${s.replaceAll('\\', '\\\\').replaceAll("'", "\\'")}'`;
const hex = (c) => `0xFF${c.replace('#', '').toUpperCase()}`;

const out = `// GENERATED by tools/gen-catalog.mjs from shared/catalog/interests.json. Do not edit.

import 'package:baglanti_agi/core/domain/catalog.dart';

const int catalogMinPick = ${catalog.minPick};
const int catalogMaxPick = ${catalog.maxPick};

const List<InterestCluster> catalogClusters = [
${catalog.clusters.map((c) => `  InterestCluster(id: ${q(c.id)}, label: ${q(c.label)}, color: ${hex(c.color)}),`).join('\n')}
];

const List<Interest> catalogInterests = [
${catalog.interests.map((i) => `  Interest(id: ${q(i.id)}, label: ${q(i.label)}, clusterId: ${q(i.cluster)}),`).join('\n')}
];
`;
writeFileSync(resolve(root, 'app/lib/core/domain/catalog.g.dart'), out);
console.log('wrote app/lib/core/domain/catalog.g.dart');
